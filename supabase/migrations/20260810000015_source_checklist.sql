-- ============================================================
-- 출처에 「체크리스트」를 더한다
--
-- ── 왜 ────────────────────────────────────────────────────
-- 체크 항목을 「업무로 올리기」로 올렸더니 출처가 **「인박스」**로 찍혔다.
-- 부모 업무의 출처를 그대로 물려받게 짜 놨기 때문이다.
--
-- 그건 틀렸다. 부모가 인박스에서 왔다는 것과, 이 업무가 체크 항목에서
-- 올라왔다는 것은 **다른 사실**이다. 출처는 「이 업무가 어디서 생겼나」이지
-- 「조상이 어디서 왔나」가 아니다.
--
-- 나중에 되짚을 때도 이게 중요하다 — 체크 항목이 업무로 커지는 일이
-- 얼마나 자주 일어나는지가 곧 「내 업무를 내가 얼마나 잘게 보고 있나」의 신호다.
-- 인박스로 뭉뚱그리면 그 신호가 사라진다.
-- ============================================================

alter table public.tasks drop constraint if exists tasks_source_check;

alter table public.tasks add constraint tasks_source_check
  check (source in (
    '내 발의', '요청받음', '일지', '인박스', '회의록', '대표지시', '절차', '체크리스트'
  ));
