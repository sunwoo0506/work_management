-- ============================================================
-- 이미 올라와 있는 업무의 출처를 바로잡는다
--
-- ── 왜 ────────────────────────────────────────────────────
-- 앞 마이그레이션(…15)은 **앞으로 만들 것**의 출처를 고쳤다.
-- 그런데 그 전에 「업무로 올리기」로 올린 업무들은 여전히 부모의 출처
-- (대개 「인박스」)를 달고 있다. 사용자가 화면에서 그걸 봤다.
--
-- 데이터를 함부로 고치지 않는 게 원칙이지만, 이건 **틀린 값이 들어간 것**이지
-- 사용자가 그렇게 정한 값이 아니다. 고치는 게 맞다.
--
-- ── 무엇을 근거로 고르나 ─────────────────────────────────
-- 「어느 체크 항목이 이 업무를 가리키고 있는가」 하나만 본다.
-- 그 줄이 있으면 그 업무는 체크 항목에서 올라온 것이 확실하다.
-- 사람이 직접 만든 업무는 그 줄이 없으므로 건드리지 않는다.
-- ============================================================

update public.tasks t
   set source = '체크리스트'
 where t.source <> '체크리스트'
   and exists (
     select 1 from public.checklist c where c.promoted_task_id = t.id
   );
