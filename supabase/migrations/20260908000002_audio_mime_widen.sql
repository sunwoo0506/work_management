-- ============================================================
-- 보관함이 받아 주는 소리 형식을 넓힌다 (2026-09-08)
--
-- ── 왜 (같은 자리에서 두 번 걸렸다) ─────────────────────────
-- 보관함은 형식 이름을 **글자 그대로** 맞춰 본다. 목록이 다섯 개뿐이었다 —
-- audio/webm · audio/ogg · audio/mp4 · audio/mpeg · audio/wav
--
-- 그런데 브라우저와 운영체제가 붙이는 이름은 훨씬 여러 가지다.
--   2026-08-16  audio/webm;codecs=opus  → 거절. 소리가 한 개도 안 올라갔다
--   2026-09-08  audio/x-m4a (아이폰 녹음) → 거절. 통째 전사가 통째로 막혔다
--
-- ── 화면에서도 고쳤는데 왜 여기까지 하나 ────────────────────
-- 화면이 이름을 목록 안의 것으로 바꿔 올리도록 고쳤다(storageMime).
-- **그래도 여기를 넓힌다.** 두 번 걸린 자리이고, 화면 쪽 한 겹만 두면
-- 새 길이 하나 생길 때마다 같은 실수를 되풀이할 수 있다.
--
-- 넓혀도 위험하지 않다 — 이 목록은 **아무 파일이나 못 올리게** 하는 것이지
-- 소리 형식을 골라내는 자리가 아니다. 전부 소리다.
--
-- ⚠️ 목록에서 빼지 않는다. 옛 회의의 소리가 그 이름으로 올라가 있다.
-- ============================================================
update storage.buckets
set allowed_mime_types = array[
  -- 원래 있던 다섯
  'audio/webm',
  'audio/ogg',
  'audio/mp4',
  'audio/mpeg',
  'audio/wav',
  -- 아이폰 녹음 (2026-09-08 에 여기서 막혔다)
  'audio/x-m4a',
  'audio/m4a',
  'audio/aac',
  -- 브라우저·운영체제마다 다르게 부르는 것들
  'audio/x-wav',
  'audio/wave',
  'audio/vnd.wave',
  'audio/mp3',
  'audio/x-mpeg',
  'audio/3gpp',
  'audio/amr',
  'audio/flac',
  'audio/x-flac',
  'video/mp4',      -- m4a 를 이렇게 부르는 기기가 있다
  'video/webm'      -- 화면 녹화기로 녹음하면 이렇게 온다
]
where id = 'meeting-audio';
