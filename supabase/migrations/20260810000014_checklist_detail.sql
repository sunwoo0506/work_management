-- ============================================================
-- 체크리스트에 「펼치면 나오는 것」을 붙인다
--
-- ── 왜 ────────────────────────────────────────────────────
-- 사용자가 써 보고 한 말:
--   *"체크리스트와 관련 세부업무의 차이를 잘 모르겠어. 체크리스트를 만들고
--     토글 형태로 관련 설명을 더 넣을 수 있게 만들면 되지 않아?
--     간단업무와 기한자료가 다 커버될 거 같아. 그렇다면 체크리스트만 남을 거고"*
--
-- 맞는 지적이다. 어제 만든 「하위 업무」와 「체크리스트」는 사용자 눈에
-- **같은 것**이었다. 둘 중 무엇을 쓸지 매번 고민해야 하면 그 자체가 비용이다.
--
-- ── 그래서 어떻게 ─────────────────────────────────────────
-- 들어가는 입구를 **체크리스트 하나로** 만든다. 항목을 펼치면
-- 설명과 기한이 나온다. 대부분의 일은 여기서 끝난다.
--
-- 다만 **버리지는 않는다.** 기한 관리가 진짜로 필요해지는 항목이 나온다 —
-- 자기 첨부파일이 붙고, 클로니와 따로 상의해야 하고, 「오늘 마감」에 떠야 하는 것.
-- 그때 항목 하나를 **업무로 올린다**(promoted_task_id). 인박스 승격과 같은 방식이다.
--
--   체크리스트 항목  ── 「업무로 올리기」 ──▶  업무 (parent_task_id = 이 업무)
--
-- 이러면 「무엇을 쓸지」 고민이 사라진다. 항상 체크리스트로 시작하고,
-- 필요해진 것만 올라간다. 절차를 부산물로 만드는 원칙(설계서 §5.2)과 같은 결이다.
-- ============================================================

-- 펼치면 나오는 설명. 「무엇을 어떻게 하는 항목인가」
alter table public.checklist add column note text;

-- 항목 자체의 기한.
-- 업무 기한과 다르다 — 업무는 8/20 인데 그 안의 「자료 요청」은 8/13 일 수 있다.
alter table public.checklist add column due_date date;

-- 업무로 올렸으면 어느 업무가 됐나.
-- on delete set null — 올린 업무를 지워도 체크 항목은 남는다.
-- 항목이 소리 없이 사라지면 "내가 뭘 하려던 거였지"가 된다.
alter table public.checklist
  add column promoted_task_id uuid references public.tasks(id) on delete set null;

create index checklist_due_idx on public.checklist (company_id, due_date)
  where due_date is not null and done = false;
