-- 같은 사용자가 같은 이름의 업체를 두 번 못 만들게 한다
--
-- 왜 필요한가 —
--   최초 진입 시드가 두 번 돌아 업체가 2건 만들어진 적이 있다.
--   개발 모드가 화면을 두 번 켜는데 중복 방지 장치가 화면과 함께
--   초기화되는 자리에 있었다 (52밀리초 간격).
--
--   앱 코드는 고쳤지만, 앱 코드의 중복 방지는 "막을 수 있는 경우만"
--   막는다. DB 에 규칙을 걸면 어떤 경로로 와도 막힌다.
--
-- 사업체는 5개까지 늘어날 수 있지만 이름이 같을 일은 없다.
-- ============================================================

create unique index companies_user_name_unique
  on public.companies (user_id, name);
