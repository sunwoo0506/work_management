-- ============================================================
-- 업무에 「작업 메모」를 붙인다
--
-- 이미 있는 detail 과 무엇이 다른가 —
--   detail = 이 일이 무엇인가.        일을 시작하기 전에 적는다
--   notes  = 하면서 알게 된 것.       일을 하는 중에 쌓인다
--
-- 둘을 한 칸에 두면 원래 설명이 메모에 묻힌다. 그리고 이 제품이
-- 남겨야 하는 건 「무엇을 했나」가 아니라 「어떻게 했나」인데,
-- 그 「어떻게」가 실제로 쌓이는 자리가 여기다.
--
-- 나중에 절차(SOP)를 뽑을 때 이 메모가 재료가 된다.
-- ============================================================

alter table public.tasks
  add column notes text;

comment on column public.tasks.notes is
  '작업 메모 — 일을 하면서 알게 된 것. detail(무엇을 하는 일인가)과 구분한다';
