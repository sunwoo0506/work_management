/**
 * 「이 칸에는 무엇을 적나」.
 *
 * 왜 한 곳에 모으나 —
 *   사용자가 실제로 업무를 하나 넣어 보고 한 말: *"상세·작업메모 같이 텍스트를 넣는
 *   공간은 어떤 내용을 정리하면 좋을지 설명을 해주면 좋을거같아. 안그러면 중복되서 사용할듯"*
 *
 *   빈 칸 세 개가 나란히 있으면 사람은 아무 데나 적는다. 그러면 3개월 뒤에
 *   같은 내용이 세 군데 나뉘어 있고 어느 게 최신인지 모른다.
 *
 *   설명 문구를 화면마다 따로 쓰면 그 문구끼리 어긋난다. 그래서 여기 한 벌만 둔다.
 *   등록 폼과 상세 서랍이 **같은 문장**을 보여 준다.
 *
 * 「이건 여기 말고 저기」를 꼭 한 줄 넣는다. 무엇을 적는지보다
 * 무엇을 **안** 적는지가 칸을 구분해 준다.
 */

